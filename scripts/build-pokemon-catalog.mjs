import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

// Snapshot metadata only; capture status is always fetched separately at runtime.
const response = await fetch("https://pokedextracker.com/api/users/wannab/dexes/allllll/captures");
if (!response.ok) throw new Error(`Unable to load catalog: ${response.status}`);
const captures = await response.json();
if (!Array.isArray(captures) || !captures.length) throw new Error("Empty Pokémon catalog");
await mkdir(resolve("src/data"), { recursive: true });
// Publish catalog metadata separately from the frequently refreshed capture status.
const catalog = captures.map(({ pokemon }) => ({
  dex_number: pokemon.dex_number,
  national_id: pokemon.national_id,
  form: pokemon.form,
  game_family: { generation: pokemon.game_family?.generation },
  name: pokemon.name,
}));
await writeFile(
  resolve("src/data/pokemon-catalog.ts"),
  `// Generated by scripts/build-pokemon-catalog.mjs. Do not edit manually.\nexport default ${JSON.stringify(catalog, null, 2)};\n`
);
console.log(`Wrote ${catalog.length} Pokémon catalog entries`);
